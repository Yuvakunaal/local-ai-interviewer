// Microphone path in real Chrome: Phonon speaks a sentence -> Chrome's fake mic replays that file -> app records,
// uploads to the LOCAL backend, faster-whisper transcribes offline -> text lands in the answer box (not auto-submitted).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { BASE, OUT, check, clickText, launch, reportIssues, shot, sleep, startBackend, textOf, waitText } from "./lib.mjs";

const be = await startBackend();
const stt = await (await fetch(`${BASE}/api/speech/stt`)).json();
if (!stt.available) { console.log(`SKIP  speech recognition not set up: ${stt.reason}`); be.proc.kill(); process.exit(0); }
const SENTENCE = "Idempotency means running the same load twice gives the same result. I use merge on a business key.";
const wav = Buffer.from(await (await fetch(`${BASE}/api/speech/synthesize`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ text: SENTENCE, voice: "Harper" }) })).arrayBuffer());
const raw = join(OUT, "phonon-24k.wav"); writeFileSync(raw, wav);
// Chrome's fake capture device wants a 48 kHz 16-bit WAV; convert Phonon's 24 kHz output locally with ffmpeg
const file = join(OUT, "fake-mic.wav");
execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", raw, "-ar", "48000", "-ac", "1", "-c:a", "pcm_s16le", file]);
const seconds = (wav.length - 44) / 48000; // 24 kHz * 2 bytes
console.log(`INFO  fake microphone clip: ${seconds.toFixed(1)}s generated by Phonon`);

await fetch(`${BASE}/api/sets/1/questions`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ text: "What is idempotency in ETL?" }) });
const created = await (await fetch(`${BASE}/api/interviews`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ set_id: 1, config: { title: "Mic test", mic_enabled: true, question_audio: "manual", max_followups: 0 } }) })).json();
const { browser, page, issues } = await launch();
// Headless Chrome ignores --use-file-for-fake-audio-capture (it records silence), so the "microphone" is a Web Audio stream
// playing the Phonon clip. Everything downstream is real: Chrome's MediaRecorder (WebM/Opus), upload, server decode, Whisper.
const clip = (await import("node:fs")).readFileSync(file).toString("base64");
await page.evaluateOnNewDocument((b64) => {
  navigator.mediaDevices.getUserMedia = async () => {
    const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
    const ctx = new AudioContext(); const buf = await ctx.decodeAudioData(bytes.buffer);
    const src = ctx.createBufferSource(); src.buffer = buf; const dest = ctx.createMediaStreamDestination();
    src.connect(dest); await ctx.resume(); src.start(); return dest.stream;
  };
}, clip);
try {
  await page.goto(`${BASE}/#/interview/${created.id}`, { waitUntil: "networkidle0" });
  await waitText(page, "Your Answer");
  await page.click('button[aria-label="Record answer"]');
  await page.waitForSelector('button[aria-label="Stop and transcribe"]');
  check(true, "recording started via MediaRecorder");
  await sleep(seconds * 1000 + 1200);
  const t0 = Date.now();
  await page.click('button[aria-label="Stop and transcribe"]');
  await page.waitForFunction(() => document.querySelector("#answer").value.length > 10, { timeout: 90000 });
  const text = await page.$eval("#answer", (e) => e.value);
  console.log(`INFO  transcript (${((Date.now() - t0) / 1000).toFixed(1)}s): ${text}`);
  check(/idempoten/i.test(text) && /same load twice/i.test(text) && /merge on a business key/i.test(text), "local Whisper transcribed the spoken answer");
  check((await textOf(page)).includes("Question 1 of 1") && (await page.$("button.primary.big")) !== null, "transcript only fills the answer box; nothing was auto-submitted");
  await shot(page, "mic-transcript");
  await clickText(page, "button", "Submit Answer");
  await page.waitForFunction(() => /Evaluating|couldn’t be evaluated|Verdict|Strengths/.test(document.body.innerText), { timeout: 15000 });
  const st = await (await fetch(`${BASE}/api/interviews/${created.id}`)).json();
  check(st.current.thread.at(-1)?.answer_source === "voice" || st.current.turn?.answer_source === "voice", "answer is recorded with source = voice");
  reportIssues(issues, ["/api/speech/synthesize net::ERR_ABORTED"]);
} catch (e) { console.log("FAIL  exception:", e.message); process.exitCode = 1; await shot(page, "mic-failure").catch(() => {}); console.log("body:", (await textOf(page).catch(() => "")).slice(0, 500)); }
finally { await browser.close(); be.proc.kill(); }
