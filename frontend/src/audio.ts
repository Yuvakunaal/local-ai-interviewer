import { synthesize } from "./api";
import { SYS_PREFIX, browserSpeech, estimateSeconds, type SystemSpeech } from "./systemVoices";

export type SpeechEngine = "phonon" | "system";

export type AudioStatus = "idle" | "loading" | "playing" | "paused" | "blocked" | "error";
export interface AudioSnapshot { status: AudioStatus; key: string | null; error: string | null; currentTime: number; duration: number; muted: boolean }

type Fetcher = (text: string, voice: string, signal: AbortSignal) => Promise<Blob>;
type Factory = (url: string) => HTMLAudioElement;

/**
 * One speaker for the whole app. Every play() supersedes the previous one (token check), aborts in-flight
 * synthesis and stops current playback, so navigating between questions can never produce overlapping or
 * stale audio.
 *
 * Two engines: "phonon" (audio generated by the local Ollama model, played through an <audio> element) and
 * "system" (the operating system's offline voices through speechSynthesis). The engine comes from the server
 * (/api/health); a voice id starting with "sys:" always means a system voice.
 */
export class AudioController {
  private token = 0;
  private audio: HTMLAudioElement | null = null;
  private url: string | null = null;
  private abort: AbortController | null = null;
  private cache = new Map<string, Blob>();
  private listeners = new Set<() => void>();
  private snap: AudioSnapshot = { status: "idle", key: null, error: null, currentTime: 0, duration: 0, muted: false };
  rate = 1;
  engine: SpeechEngine | null = null;          // unknown until the server has told us
  private engineKnown: Promise<void>;
  private engineResolve!: () => void;
  // system-voice state: what is being spoken and where we are, so pause/speed/mute can resume mid-sentence
  private sysActive = false;
  private sysGen = 0;
  private sysText = "";
  private sysVoice = "default";
  private sysOffset = 0;
  private sysTotal = 0;

  constructor(
    private fetcher: Fetcher = synthesize,
    private factory: Factory = (u) => new Audio(u),
    private system: SystemSpeech | null | (() => SystemSpeech | null) = browserSpeech,
  ) {
    this.engineKnown = new Promise((r) => { this.engineResolve = r; });
  }

  private sys(): SystemSpeech | null { return typeof this.system === "function" ? this.system() : this.system; }

  setEngine(e: SpeechEngine) {
    this.engine = e;
    this.engineResolve();
  }

  subscribe = (fn: () => void) => { this.listeners.add(fn); return () => { this.listeners.delete(fn); }; };
  getSnapshot = () => this.snap;
  private set(s: Partial<AudioSnapshot>) { this.snap = { ...this.snap, ...s }; this.listeners.forEach((l) => l()); }

  private release() {
    this.abort?.abort();
    this.abort = null;
    if (this.audio) { this.audio.onended = null; this.audio.onerror = null; this.audio.ontimeupdate = null; this.audio.onloadedmetadata = null; this.audio.pause(); this.audio = null; }
    if (this.url) { URL.revokeObjectURL(this.url); this.url = null; }
    if (this.sysActive) { this.sysActive = false; this.sysGen++; this.sys()?.cancel(); }
  }

  stop() {
    this.token++;
    this.release();
    this.set({ status: "idle", key: null, error: null, currentTime: 0, duration: 0 });
  }

  /** Pause / resume the current clip without losing the position. */
  togglePause() {
    if (this.sysActive) {
      if (this.snap.status === "playing") { this.sysGen++; this.sys()?.cancel(); this.set({ status: "paused" }); }   // cancel + resume-from-offset works on every OS
      else if (this.snap.status === "paused") this.speakSystem(this.token, this.sysOffset);
      return;
    }
    const a = this.audio;
    if (!a) return;
    if (this.snap.status === "playing") { a.pause(); this.set({ status: "paused" }); }
    else if (this.snap.status === "paused") { void a.play().then(() => this.set({ status: "playing" }), () => this.set({ status: "blocked" })); }
  }

  setMuted(m: boolean) {
    if (this.audio) this.audio.muted = m;
    this.set({ muted: m });
    if (this.sysSpeaking()) this.speakSystem(this.token, this.sysOffset);   // volume is fixed per utterance, so continue from here
  }

  setRate(r: number) {
    this.rate = r;
    if (this.audio) { this.audio.playbackRate = r; }
    if (this.sysSpeaking()) this.speakSystem(this.token, this.sysOffset);    // speed is fixed per utterance, so continue from here
  }

  private sysSpeaking() { return this.sysActive && (this.snap.status === "playing" || this.snap.status === "loading"); }

  /** Speak sysText from `offset` (0 = start). Older utterances are ignored through sysGen. */
  private speakSystem(my: number, offset: number) {
    const sys = this.sys();
    if (!sys) { this.set({ status: "error", error: "This browser has no built-in speech voices." }); return; }
    const gen = ++this.sysGen;
    const live = () => my === this.token && gen === this.sysGen;
    this.sysActive = true;
    this.sysOffset = offset;
    this.sysTotal = estimateSeconds(this.sysText, this.rate);
    const frac = (i: number) => (this.sysText.length ? Math.min(1, i / this.sysText.length) : 0);
    this.set({ status: "loading", duration: this.sysTotal, currentTime: this.sysTotal * frac(offset) });
    sys.cancel();   // never queue behind an older utterance
    sys.speak(this.sysText.slice(offset), {
      voiceId: this.sysVoice.startsWith(SYS_PREFIX) ? this.sysVoice : null,
      rate: this.rate,
      volume: this.snap.muted ? 0 : 1,
      onstart: () => { if (live()) this.set({ status: "playing" }); },
      onboundary: (i) => { if (live()) { this.sysOffset = offset + i; this.set({ status: "playing", currentTime: this.sysTotal * frac(offset + i) }); } },
      onend: () => { if (live()) { this.sysActive = false; this.set({ status: "idle", key: null, currentTime: 0 }); } },
      onerror: (code) => {
        if (!live() || code === "interrupted" || code === "canceled") return;
        if (code === "not-allowed") this.set({ status: "blocked", error: "Your browser blocked autoplay. Press Play." });
        else this.set({ status: "error", error: code === "synthesis-unavailable" || code === "voice-unavailable" ? "This computer has no offline voice installed." : "Speech failed." });
      },
    });
  }

  /** key identifies what is being spoken (so the UI can show which item is playing). */
  async play(key: string, text: string, voice: string): Promise<void> {
    const my = ++this.token;
    this.release();
    this.set({ status: "loading", key, error: null, currentTime: 0, duration: 0 });
    if (this.engine === null && !voice.startsWith(SYS_PREFIX)) {
      await Promise.race([this.engineKnown, new Promise((r) => setTimeout(r, 2500))]);   // the server decides; don't guess too early
      if (my !== this.token) return;
    }
    if (voice.startsWith(SYS_PREFIX) || this.engine === "system") {
      this.sysText = text;
      this.sysVoice = voice;
      this.speakSystem(my, 0);
      return;
    }
    const cacheKey = `${voice}\0${text}`;
    try {
      let blob = this.cache.get(cacheKey);
      if (!blob) {
        this.abort = new AbortController();
        blob = await this.fetcher(text, voice, this.abort.signal);
        if (my !== this.token) return;                    // superseded while generating
        this.cache.set(cacheKey, blob);
        if (this.cache.size > 24) this.cache.delete(this.cache.keys().next().value as string);
      }
      this.url = URL.createObjectURL(blob);
      const audio = this.factory(this.url);
      audio.playbackRate = this.rate;
      audio.preservesPitch = true;
      audio.muted = this.snap.muted;
      audio.onloadedmetadata = () => { if (my === this.token) this.set({ duration: Number.isFinite(audio.duration) ? audio.duration : 0 }); };
      audio.ontimeupdate = () => { if (my === this.token) this.set({ currentTime: audio.currentTime }); };
      audio.onended = () => { if (my === this.token) this.set({ status: "idle", key: null, currentTime: 0 }); };
      audio.onerror = () => { if (my === this.token) this.set({ status: "error", error: "The browser could not play this audio." }); };
      this.audio = audio;
      try {
        await audio.play();
      } catch (e) {
        if (my !== this.token) return;
        if ((e as Error).name === "NotAllowedError") { this.set({ status: "blocked", error: "Your browser blocked autoplay. Press Play." }); return; }
        throw e;
      }
      if (my === this.token) this.set({ status: "playing" });
    } catch (e) {
      if (my !== this.token || (e as Error).name === "AbortError") return;
      this.set({ status: "error", error: (e as Error).message || "Speech failed." });
    }
  }
}

export const speaker = new AudioController();
